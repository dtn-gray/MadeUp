import { createReadStream } from 'node:fs';
import { lstat, readdir, readFile, writeFile } from 'node:fs/promises';
import { createServer } from 'node:http';
import { extname, join } from 'node:path';
import { pipeline } from 'node:stream/promises';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('.', import.meta.url));
const products = join(root, 'products');
const pages = new Map([
  ['/', 'index.html'],
  ['/index.html', 'index.html'],
  ['/artwork.html', 'artwork.html'],
  ['/products.js', 'products.js'],
  ['/sketch.js', 'sketch.js'],
  ['/vendor/p5.min.js', 'vendor/p5.min.js']
]);
const imageTypes = new Map([
  ['.apng', 'image/apng'], ['.avif', 'image/avif'], ['.bmp', 'image/bmp'],
  ['.gif', 'image/gif'], ['.heic', 'image/heic'], ['.heif', 'image/heif'],
  ['.ico', 'image/x-icon'], ['.jfif', 'image/jpeg'], ['.jpeg', 'image/jpeg'],
  ['.jpg', 'image/jpeg'], ['.jxl', 'image/jxl'], ['.png', 'image/png'],
  ['.svg', 'image/svg+xml'], ['.tif', 'image/tiff'], ['.tiff', 'image/tiff'],
  ['.webp', 'image/webp']
]);

const imageType = (name) => imageTypes.get(extname(name).toLowerCase());

async function imageNames(directory) {
  try {
    const entries = await readdir(directory, { withFileTypes: true });
    return entries.filter((entry) => entry.isFile() && imageType(entry.name))
      .map((entry) => entry.name).sort();
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
    return [];
  }
}

async function catalog() {
  const [images, samples] = await Promise.all([
    imageNames(products),
    imageNames(join(products, 'samples'))
  ]);
  return { images, samples: samples.map((name) => 'samples/' + name) };
}

async function previewImage(path) {
  const bytes = await readFile(join(products, path));
  return { path, type: imageType(path), base64: bytes.toString('base64') };
}

async function writeCatalogs() {
  const listing = await catalog();
  const [images, samples] = await Promise.all(
    [listing.images, listing.samples].map((paths) => Promise.all(paths.map(previewImage))),
  );
  // The script stores the same image bytes for browsers that open index.html via file://.
  const preview = 'globalThis.packagedProductCatalog = ' + JSON.stringify({ images, samples }, null, 2) + ';\n';
  await Promise.all([
    writeFile(join(products, 'catalog.json'), JSON.stringify(listing, null, 2) + '\n'),
    writeFile(join(products, 'preview-catalog.js'), '// Generated by node serve.mjs --write-catalog.\n' + preview),
  ]);
}

async function sendFile(request, response, path, type) {
  const file = await lstat(path);
  if (!file.isFile()) {
    response.writeHead(404).end();
    return;
  }
  response.writeHead(200, {
    'Content-Type': type,
    'Content-Length': file.size,
    'Cache-Control': 'no-store',
    'X-Content-Type-Options': 'nosniff'
  });
  if (request.method === 'HEAD') response.end();
  else await pipeline(createReadStream(path), response);
}

async function sendCatalog(request, response) {
  // Scan the folder for each catalogue request so new photos appear after a reload.
  const listing = JSON.stringify(await catalog());
  response.writeHead(200, {
    'Content-Type': 'application/json; charset=utf-8',
    'Content-Length': Buffer.byteLength(listing),
    'Cache-Control': 'no-store'
  }).end(request.method === 'HEAD' ? undefined : listing);
}

function sendError(response, error) {
  if (response.headersSent) return response.destroy();
  const status = error instanceof URIError ? 400 : error.code === 'ENOENT' ? 404 : 500;
  if (status === 500) console.error(error.message);
  response.writeHead(status).end();
}

async function route(request, response) {
  const path = decodeURIComponent(new URL(request.url, 'http://localhost').pathname);
  if (path === '/products/catalog.json') return sendCatalog(request, response);
  const page = pages.get(path);
  if (page) {
    const type = page.endsWith('.js') ? 'text/javascript; charset=utf-8' : 'text/html; charset=utf-8';
    return sendFile(request, response, join(root, page), type);
  }
  const product = path.match(/^\/products\/(?:(samples)\/)?([^/\\:]+)$/);
  const type = product && imageType(product[2]);
  if (type) return sendFile(request, response, join(products, product[1] ?? '', product[2]), type);
  response.writeHead(404).end();
}

async function serve(request, response) {
  if (request.method !== 'GET' && request.method !== 'HEAD') {
    response.writeHead(405, { Allow: 'GET, HEAD' }).end();
    return;
  }
  try {
    await route(request, response);
  } catch (error) {
    sendError(response, error);
  }
}

if (process.argv[2] === '--write-catalog') {
  await writeCatalogs();
} else {
  const port = Number(process.argv[2] ?? 8787);
  const server = createServer(serve);
  server.listen(port, '127.0.0.1', () => console.log('Artwork at http://127.0.0.1:' + server.address().port + '/'));
}
